// The chart with Capybara's preset: only what the manifest declares, CRDs
// kept on uninstall, no API server, Dex, notifications or running
// ApplicationSet controller, every container "restricted", and the proxy
// settings reaching the repo server.
func TestArgoCDChart(t *testing.T) {
	spec := argoSpec(t)
	objs := renderArgo(t, spec, map[string]any{"httpsProxy": "http://proxy.corp:3128", "noProxy": ".svc,.cluster.local"})
	rules, nsRules := InstallerRules(spec, v1alpha1.ModeInstall, nil, spec.Chart.Namespace)
	rules = append(rules, nsRules...)
	var crds, deployments []string
	for _, o := range objs {
		gvr := guessResource(o)
		for _, verb := range []string{"create", "delete"} {
			if !allows(rules, gvr.Group, gvr.Resource, verb) {
				t.Errorf("%s %s %s: not declared", verb, o.GetKind(), o.GetName())
			}
		}
		switch o.GetKind() {
		case "CustomResourceDefinition":
			crds = append(crds, o.GetName())
			if o.GetAnnotations()[HelmResourcePolicy] != "keep" {
				t.Errorf("CRD %s is not kept on uninstall", o.GetName())
			}
		case "Deployment", "StatefulSet":
			replicas, _, _ := unstructured.NestedFieldNoCopy(o.Object, "spec", "replicas")
			deployments = append(deployments, fmt.Sprintf("%s=%v", o.GetName(), replicas))
			pod, _, _ := unstructured.NestedMap(o.Object, "spec", "template", "spec")
			if nonRoot, _, _ := unstructured.NestedBool(pod, "securityContext", "runAsNonRoot"); !nonRoot {
				t.Errorf("%s: pod not runAsNonRoot", o.GetName())
			}
			if sp, _, _ := unstructured.NestedString(pod, "securityContext", "seccompProfile", "type"); sp != "RuntimeDefault" {
				t.Errorf("%s: seccomp %q", o.GetName(), sp)
			}
			containers, _, _ := unstructured.NestedSlice(pod, "containers")
			inits, _, _ := unstructured.NestedSlice(pod, "initContainers")
			for _, c := range append(containers, inits...) {
				cm := c.(map[string]any)
				esc, found, _ := unstructured.NestedBool(cm, "securityContext", "allowPrivilegeEscalation")
				drop, _, _ := unstructured.NestedStringSlice(cm, "securityContext", "capabilities", "drop")
				if !found || esc || !slices.Contains(drop, "ALL") {
					t.Errorf("%s/%s: not restricted (escalation %v, drop %v)", o.GetName(), cm["name"], esc, drop)
				}
				if cm["name"] == "repo-server" {
					env, _ := json.Marshal(cm["env"])
					if !strings.Contains(string(env), `{"name":"HTTPS_PROXY","value":"http://proxy.corp:3128"}`) || !strings.Contains(string(env), `"value":".svc,.cluster.local"`) {
						t.Errorf("repo server env = %s", env)
					}
				}
			}
			if vols, _, _ := unstructured.NestedSlice(pod, "volumes"); strings.Contains(fmt.Sprint(vols), "hostPath") {
				t.Errorf("%s: hostPath volume", o.GetName())
			}
		case "Job":
			t.Errorf("unexpected Job %s (Redis's password is generated by Capybara)", o.GetName())
		}
		if strings.Contains(o.GetName(), "server") && o.GetKind() == "Deployment" && o.GetName() != "argocd-repo-server" {
			t.Errorf("unexpected %s %s", o.GetKind(), o.GetName())
		}
		if strings.Contains(o.GetName(), "dex") || strings.Contains(o.GetName(), "notifications") {
			t.Errorf("unexpected %s %s", o.GetKind(), o.GetName())
		}
	}
	slices.Sort(crds)
	if fmt.Sprint(crds) != "[applications.argoproj.io applicationsets.argoproj.io appprojects.argoproj.io]" {
		t.Errorf("CRDs = %v", crds)
	}
	slices.Sort(deployments)
	if fmt.Sprint(deployments) != "[argocd-application-controller=1 argocd-applicationset-controller=0 argocd-redis=1 argocd-repo-server=1]" {
		t.Errorf("workloads = %v", deployments)
	}
}

// The default AppProject is locked (a chart hook): no sources, destinations
// or kinds, and no Applications from any other namespace.
func TestArgoCDDefaultProjectIsLocked(t *testing.T) {
	spec := argoSpec(t)
	var found bool
	for _, o := range renderArgo(t, spec, nil) {
		if o.GetKind() != "AppProject" {
			continue
		}
		if o.GetName() != "default" || o.GetNamespace() != "argocd" {
			t.Errorf("unexpected AppProject %s/%s", o.GetNamespace(), o.GetName())
		}
		found = true
		for _, f := range []string{"sourceRepos", "destinations", "sourceNamespaces", "clusterResourceWhitelist"} {
			if v, _, _ := unstructured.NestedSlice(o.Object, "spec", f); len(v) != 0 {
				t.Errorf("default.%s = %v", f, v)
			}
		}
		black, _, _ := unstructured.NestedSlice(o.Object, "spec", "namespaceResourceBlacklist")
		if fmt.Sprint(black) != "[map[group:* kind:*]]" {
			t.Errorf("default.namespaceResourceBlacklist = %v", black)
		}
		if !strings.Contains(o.GetAnnotations()["helm.sh/hook"], "post-upgrade") || o.GetLabels()[v1alpha1.LabelPlugin] != "argocd" {
			t.Errorf("default AppProject: annotations %v, labels %v", o.GetAnnotations(), o.GetLabels())
		}
	}
	if !found {
		t.Fatal("no default AppProject")
	}
}

// Each Project's generated AppProject: Applications only from its own
// namespace, into it, on this cluster; no cluster kinds; never quota,
// limits, network policies or role bindings.
func TestArgoCDProjectAppProject(t *testing.T) {
	spec := argoSpec(t)
	objs := spec.Permissions.Project.Objects
	if len(objs) != 1 || !objs[0].InPluginNamespace || objs[0].Resource != "appprojects" {
		t.Fatalf("project objects = %+v", objs)
	}
	o, err := RenderProjectObject(objs[0], ProjectRef{Name: "team-a", Namespace: "team-a-dev"}, "dev-1", "argocd")
	if err != nil {
		t.Fatal(err)
	}
	if o.GetName() != "capybara-team-a" || o.GetNamespace() != "argocd" {
		t.Errorf("AppProject %s/%s", o.GetNamespace(), o.GetName())
	}
	sources, _, _ := unstructured.NestedStringSlice(o.Object, "spec", "sourceNamespaces")
	dest, _, _ := unstructured.NestedSlice(o.Object, "spec", "destinations")
	white, found, _ := unstructured.NestedSlice(o.Object, "spec", "clusterResourceWhitelist")
	black, _, _ := unstructured.NestedSlice(o.Object, "spec", "namespaceResourceBlacklist")
	if fmt.Sprint(sources) != "[team-a-dev]" || fmt.Sprint(dest) != "[map[namespace:team-a-dev server:https://kubernetes.default.svc]]" || !found || len(white) != 0 {
		t.Errorf("sources %v, destinations %v, cluster kinds %v (%v)", sources, dest, white, found)
	}
	var kinds []string
	for _, b := range black {
		kinds = append(kinds, b.(map[string]any)["kind"].(string))
	}
	if fmt.Sprint(kinds) != "[ResourceQuota LimitRange NetworkPolicy RoleBinding]" {
		t.Errorf("refused kinds = %v", kinds)
	}
	// Installer: the AppProjects in Argo CD's namespace only, in connect mode.
	_, ns := InstallerRules(spec, v1alpha1.ModeConnect, nil, "openshift-gitops")
	if !allows(ns, "argoproj.io", "appprojects", "create") {
		t.Error("connect installer cannot create the generated AppProjects")
	}
}

// Capybara never holds a write permission on ApplicationSets.
func TestArgoCDNoApplicationSetWrites(t *testing.T) {
	spec := argoSpec(t)
	for name, rules := range map[string][]v1alpha1.PolicyRule{
		"console": spec.Permissions.Console.ClusterRules,
		"project": spec.Permissions.Project.Rules,
	} {
		for _, verb := range []string{"get", "create", "update", "patch", "delete"} {
			if allows(toRBAC(rules), "argoproj.io", "applicationsets", verb) {
				t.Errorf("%s grants %s on applicationsets", name, verb)
			}
		}
	}
	for _, mode := range []v1alpha1.InstallMode{v1alpha1.ModeInstall, v1alpha1.ModeConnect} {
		c, n := InstallerRules(spec, mode, nil, "argocd")
		for _, verb := range []string{"create", "update", "patch", "delete"} {
			if allows(append(c, n...), "argoproj.io", "applicationsets", verb) {
				t.Errorf("%s installer may %s applicationsets", mode, verb)
			}
		}
	}
}

