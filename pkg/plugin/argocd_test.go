func TestArgoCDActions(t *testing.T) {
	f := newArgoAPI(t, false)
	ctx := context.Background()
	act := func(name string, req ActionRequest) (int, map[string]any) {
		req.Namespace, req.Name, req.UID = "team-a-dev", "web", "a1"
		return f.do(t, http.MethodPost, "/api/clusters/dev-1/plugin-actions/argocd/"+name, req)
	}
	get := func() *unstructured.Unstructured {
		o, _ := f.dyn.Resource(appGVR).Namespace("team-a-dev").Get(ctx, "web", metav1.GetOptions{})
		return o
	}

	if code, body := act("refresh", ActionRequest{}); code != 200 || get().GetAnnotations()["argocd.argoproj.io/refresh"] != "normal" {
		t.Errorf("refresh: %d %v", code, body)
	}
	// Prune asks for the name; the operation records the user.
	if code, body := act("sync", ActionRequest{Inputs: map[string]any{"prune": true}}); code != http.StatusBadRequest || !strings.Contains(fmt.Sprint(body["error"]), "type the name web") {
		t.Errorf("prune without the name: %d %v", code, body)
	}
	if code, body := act("sync", ActionRequest{Inputs: map[string]any{"prune": true, "revision": "v2"}, ConfirmName: "web"}); code != 200 {
		t.Fatalf("sync: %d %v", code, body)
	}
	op, _, _ := unstructured.NestedMap(get().Object, "operation")
	if fmt.Sprint(op) != "map[initiatedBy:map[username:dev] sync:map[prune:true revision:v2]]" {
		t.Errorf("operation = %v", op)
	}
	// While it runs, no second sync or rollback.
	if code, body := act("sync", ActionRequest{Inputs: map[string]any{"prune": false}}); code != http.StatusConflict || !strings.Contains(fmt.Sprint(body["error"]), "operation is set") {
		t.Errorf("sync during a sync: %d %v", code, body)
	}
	app := get()
	unstructured.RemoveNestedField(app.Object, "operation")
	_, _ = f.dyn.Resource(appGVR).Namespace("team-a-dev").Update(ctx, app, metav1.UpdateOptions{})

	// Without the operation field: a sync without a revision leaves it out.
	if code, _ := act("sync", ActionRequest{Inputs: map[string]any{"prune": false}}); code != 200 {
		t.Fatal("plain sync refused")
	}
	if rev, found, _ := unstructured.NestedFieldNoCopy(get().Object, "operation", "sync", "revision"); found {
		t.Errorf("revision = %v", rev)
	}
	app = get()
	unstructured.RemoveNestedField(app.Object, "operation")
	_, _ = f.dyn.Resource(appGVR).Namespace("team-a-dev").Update(ctx, app, metav1.UpdateOptions{})

	// Sync policy: self-heal needs auto-sync; auto-prune asks for the name.
	if code, _ := act("self-heal-on", ActionRequest{}); code != http.StatusConflict {
		t.Errorf("self-heal without auto-sync: %d", code)
	}
	if code, body := act("auto-sync-on", ActionRequest{}); code != 200 {
		t.Fatalf("auto-sync on: %d %v", code, body)
	}
	if code, _ := act("auto-sync-on", ActionRequest{}); code != http.StatusConflict {
		t.Errorf("auto-sync on twice: %d", code)
	}
	if code, _ := act("auto-prune-on", ActionRequest{}); code != http.StatusBadRequest {
		t.Errorf("auto-prune without the name: %d", code)
	}
	if code, _ := act("auto-prune-on", ActionRequest{ConfirmName: "web"}); code != 200 {
		t.Error("auto-prune on refused")
	}
	if code, _ := act("self-heal-on", ActionRequest{}); code != 200 {
		t.Error("self-heal on refused")
	}
	automated, _, _ := unstructured.NestedMap(get().Object, "spec", "syncPolicy", "automated")
	if fmt.Sprint(automated) != "map[prune:true selfHeal:true]" {
		t.Errorf("automated = %v", automated)
	}
	// Rollback is refused while auto-sync is on (it would sync back).
	if code, body := act("sync-revision", ActionRequest{Inputs: map[string]any{"revision": "abc123"}}); code != http.StatusConflict || !strings.Contains(fmt.Sprint(body["error"]), "spec.syncPolicy.automated is set") {
		t.Errorf("rollback with auto-sync: %d %v", code, body)
	}
	if code, _ := act("auto-sync-off", ActionRequest{}); code != 200 {
		t.Fatal("auto-sync off refused")
	}
	if _, found, _ := unstructured.NestedFieldNoCopy(get().Object, "spec", "syncPolicy", "automated"); found {
		t.Error("automated kept after auto-sync off")
	}
	if code, body := act("sync-revision", ActionRequest{Inputs: map[string]any{"revision": "abc123"}}); code != 200 {
		t.Errorf("rollback: %d %v", code, body)
	}
	if rev, _, _ := unstructured.NestedString(get().Object, "operation", "sync", "revision"); rev != "abc123" {
		t.Errorf("rollback revision = %q", rev)
	}
	// Audited as argocd.<action>.
	recs, _ := f.store.List(ctx, audit.Filter{})
	var names []string
	for _, r := range recs {
		names = append(names, r.Action+"="+string(r.Result))
	}
	if !slices.Contains(names, "argocd.sync-revision=success") || !slices.Contains(names, "argocd.auto-prune-on=failure") {
		t.Errorf("audit = %v", names)
	}
}
